create or replace view public.active_product_catalog as
select
  p.id,
  p.name,
  c.name as category,
  p.description,
  p.top_notes,
  p.heart_notes,
  p.base_notes,
  p.is_best_seller,
  p.is_featured,
  pi.image_url as image,
  json_agg(json_build_object('id', pv.id, 'size', pv.size, 'price_paise', pv.price_paise, 'sku', pv.sku, 'stock_quantity', pv.stock_quantity) order by pv.price_paise) as variants
from public.products p
join public.categories c on c.id = p.category_id
left join public.product_images pi on pi.product_id = p.id and pi.is_primary = true
join public.product_variants pv on pv.product_id = p.id and pv.is_active = true
where p.is_active = true
group by p.id, c.name, pi.image_url;

grant select on public.active_product_catalog to anon, authenticated;
grant insert on public.newsletter_subscribers to anon, authenticated;
